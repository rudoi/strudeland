#[inline]
fn mh_uu(a: U128, b: U128) -> U128 {
    let (ah, al) = ((a >> 64) as U64, a as U64);
    let (bh, bl) = ((b >> 64) as U64, b as U64);
    let ahbh = ah as U128 * bh as U128;
    let ahbl = ah as U128 * bl as U128;
    let albh = al as U128 * bh as U128;
    ahbh.wrapping_add((ahbl >> 64).wrapping_add(albh >> 64))
}

/* Return Sr such that Sr/2^128 approximates sin2pi(r), for 0 <= r < 2^-14,
where u/2^128 approximates r'=8*r, u2/2^128 approximates r'^2,
u4/2^128 approximates r'^4, and u2h = floor(u2/2^64). */
#[inline]
fn eval_ps(u: U128, u2: U128, u2h: U128, u4: U128) -> U128 {
    /* we perform the computation in fixed point, where each variable a is
    interpreted as a/2^128, thus multiplying two variables a and b mean
    taking floor(a*b/2^128) */
    // since signs of coefficients are alternating, and each new coefficient
    // dominates the lower terms, we subtract each time the lower terms from
    // the (absolute value of) the new coefficient
    // use Estrin's scheme: evaluate separately the degree-{1,3} part,
    // and the degree-{5,7} part, multiplied by r^4
    let mut sh = PS[2].wrapping_sub(PS[3].wrapping_mul(u2h));
    sh = mh_uu(sh, u4);
    let mut s = mh_uu(PS[1], u2);
    s = PS[0].wrapping_sub(s);
    s = s.wrapping_add(sh);
    mh_uu(s, u) // multiply by r
}

/* Return Cr such that Cr/2^128 approximates cos2pi(r), for 0 <= r < 2^-14,
where u2/2^128 approximates r'^2, u4/2^128 approximates r'^4, and
u2h = floor(u2/2^64), with r'=8*r. */
#[inline]
fn eval_pc(u2: U128, u2h: U128, u4: U128) -> U128 {
    // use Estrin's scheme
    let mut sh = PC[3].wrapping_sub(u2h.wrapping_mul(PC[4]));
    sh = PC[2].wrapping_sub(mh_uu(sh, u2));
    let mut s = mh_uu(PC[1], u2);
    s = PC[0].wrapping_sub(s);
    s.wrapping_add(mh_uu(sh, u4))
}

// argument reduction for |x| >= 2^31
// return k and r such that
// x/(2pi) mod 1 = k/2^15 + r + s with 0 <= r < 2^-15 and 0 <= s < 2^-67.988
fn reduce_large(r: &mut f64, x: f64) -> u64 {
    let t = x.to_bits();
    let e = ((t >> 52) & 0x7ff) as i32; /* 1054 <= e <= 2046 */
    let m: u64 = (1u64 << 52) | (t & 0xfffffffffffff);
    // x = m * 2^(e-1075)
    /* _T[j] corresponds to _T[j]/2^(64*j) thus _T[j]*x corresponds to
    m*_T[j]*2^(e-1075-64*j). To get a non-zero fractional value,
    we need e-1075-64*j < 0, thus 64*j > e-1075 or 64*j >= e-1074. */
    let i = ((e - 1011) / 64) as usize; // i = ceil((e-1074)/64), 0 <= i <= 16
    let f = ((e - 1011) & 0x3f) as u32;
    /* the number of fractional bits from m*_T[i] is 64-f, thus we have to
    shift _T[i] by f bits to get 64 fractional bits */
    let (v0, v1) = if f == 0 {
        (T[i], T[i + 1])
    } else {
        (
            (T[i] << f) | (T[i + 1] >> (64 - f)),
            (T[i + 1] << f) | (T[i + 2] >> (64 - f)),
        )
    };
    /* Remark: computing directly u with 128-bit arithmetic from _T[i],
    _T[i+1] and _T[i+2] is slower (surely because 128-bit arithmetic is
    emulated.) */
    let mut u: U128 = v1 as U128 | ((v0 as U128) << 64);
    u = (m as U128).wrapping_mul(u);
    // round r to nearest, where 0x810000000000000 = 2^59 + 2^52
    const MAGIC: U128 = (1u128 << 112) + 0x810000000000000;
    u = u.wrapping_add(MAGIC);
    let tf = ((u << 15) >> 75) as u64 as f64; // next 53 bits of u after the first 15
    *r = tf * 3.3881317890172014e-21 - 1.52587890625e-05;
    (u >> 113) as u64
    // since we return 15 bits in i and 53 in h, the accuracy is at most 2^-68
}

#[inline]
fn fasttwosum(x: f64, y: f64, e: &mut f64) -> f64 {
    let s = x + y;
    let z = s - x;
    *e = y - z;
    s
}

#[inline]
fn fastsum(xh: f64, xl: f64, yh: f64, yl: f64, e: &mut f64) -> f64 {
    let mut sl = 0.0;
    let sh = fasttwosum(xh, yh, &mut sl);
    *e = (xl + yl) + sl;
    sh
}

#[inline]
fn muldd(xh: f64, xl: f64, ch: f64, cl: f64, l: &mut f64) -> f64 {
    let ahhh = xh * ch;
    *l = (xh * cl + xl * ch) + xh.mul_add(ch, -ahhh);
    ahhh
}

