// This code is adapted from sin.c. It copies the following tables
// from sin.c, which can be shared between both functions:
//   pih, pil      - argument reduction for x < 2^31
//   _T            - for Payne-Hanek argument reduction
//   PS, PC        - polynomials for the accurate path
//   U1, U2        - tables for the fast path
//   S1u, S2u, C1u - tables for the accurate path
//
// Port notes: round-to-nearest only, errno and FE_INVALID dropped, `__builtin_fma` is
// `f64::mul_add`, `roundeven` is `f64::round_ties_even`, and the C `u128` arithmetic (which wraps
// modulo 2^128) uses the `wrapping_*` operations.

type U128 = u128;
type U64 = u64;

/// `U128(l,h)` of the C source (little endian).
const fn u128_lh(l: u64, h: u64) -> u128 {
    ((h as u128) << 64) | l as u128
}

// round (-1)^s*r/2^128 to double, assuming r is non-zero and not in the
// subnormal region
#[inline]
fn u128_tod(r: U128, s: usize) -> f64 {
    let sh = ((r >> 64) as u64).leading_zeros() as u64;
    /* since the smallest distance from a binary64 number to a multiple of pi/2
    is 2^-60.888 (see [1]), the smallest value of r/2^128 is about 2^-60.888
    too (taking into account approximation errors), thus sh <= 60.
    This proves that r>>64 cannot be 0, thus __builtin_clzll() is valid. */
    let h = (r >> (75 - sh)) as u64; // upper 53 non-zero bits
    let rbit = ((r >> (74 - sh)) & 1) as usize; // round bit
    const SGN: [f64; 2] = [1.1102230246251565e-16, -1.1102230246251565e-16];
    let v = f64::from_bits(SGN[s].to_bits() - (sh << 52)); // scale by 2^-sh
    const LOW: [f64; 2] = [0.375, 0.75];
    let a = h as f64 * v;
    let b = LOW[rbit] * v;
    /* Assume sin(x) > 0, thus s=0. When rbit is 0, we have b < ulp(a)/2,
    and the result is rounded to a to nearest, which is what we want.
    When rbit is 1, we have b > ulp(a)/2, and the result is rounded to
    nextup(a), which is what we want too.
    In both case it is proven in sin.pdf that the approximation error
    cannot make the result cross a rounding boundary, except maybe for
    hard-to-round cases, which are checked by sin.wc. */
    a + b
}

