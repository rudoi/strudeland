// Correctly rounded log(1+x) for binary64 (round-to-nearest only: errno, the floating-point
// environment and the other rounding modes are dropped). C pointer outputs (`double *l`) become
// a returned `(high, low)` pair; `__builtin_fma` is `f64::mul_add`; `roundeven` is
// `round_ties_even`. Hex float constants are written as their exact shortest decimal.

#![allow(clippy::excessive_precision, clippy::approx_constant)]

#[inline(always)]
fn fasttwosum(x: f64, y: f64) -> (f64, f64) {
    let s = x + y;
    let z = s - x;
    (s, y - z)
}

#[inline(always)]
fn twosum(xh: f64, ch: f64) -> (f64, f64) {
    let s = xh + ch;
    let d = s - xh;
    (s, (ch - d) + (xh + (d - s)))
}

#[inline(always)]
fn fastsum(xh: f64, xl: f64, yh: f64, yl: f64) -> (f64, f64) {
    let (sh, sl) = fasttwosum(xh, yh);
    (sh, (xl + yl) + sl)
}

#[inline(always)]
fn sum(xh: f64, xl: f64, ch: f64, cl: f64) -> (f64, f64) {
    let (sh, sl) = twosum(xh, ch);
    (sh, (xl + cl) + sl)
}

#[inline(always)]
fn muldd(xh: f64, xl: f64, ch: f64, cl: f64) -> (f64, f64) {
    let ahhh = ch * xh;
    (ahhh, (cl * xh + ch * xl) + ch.mul_add(xh, -ahhh))
}

#[inline(always)]
fn mulddd(x: f64, ch: f64, cl: f64) -> (f64, f64) {
    let ahhh = ch * x;
    (ahhh, cl * x + ch.mul_add(x, -ahhh))
}

/// `l` is the input low part; returns `(high, low)`.
#[inline(always)]
fn polydd(xh: f64, xl: f64, n: usize, c: &[[f64; 2]], l: f64) -> (f64, f64) {
    let mut i = n - 1;
    let (mut ch, l) = fasttwosum(c[i][0], l);
    let mut cl = c[i][1] + l;
    while i > 0 {
        i -= 1;
        (ch, cl) = muldd(xh, xl, ch, cl);
        (ch, cl) = fastsum(c[i][0], c[i][1], ch, cl);
    }
    (ch, cl)
}

/// `l` is the input low part; returns `(high, low)`.
#[inline(always)]
fn polyddd(x: f64, n: usize, c: &[[f64; 2]], l: f64) -> (f64, f64) {
    let mut i = n - 1;
    let (mut ch, l) = fasttwosum(c[i][0], l);
    let mut cl = c[i][1] + l;
    while i > 0 {
        i -= 1;
        (ch, cl) = mulddd(x, ch, cl);
        (ch, cl) = fastsum(c[i][0], c[i][1], ch, cl);
    }
    (ch, cl)
}

