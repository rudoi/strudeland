#[inline(never)]
fn as_expm1_database(x: f64, f: f64) -> f64 {
    let ix = x.to_bits();
    let mut a: i32 = 0;
    let mut b: i32 = DB.len() as i32 - 1;
    let mut m = (a + b) / 2;
    while a <= b {
        let cm = DB[m as usize].to_bits();
        if cm < ix {
            a = m + 1;
        } else if cm == ix {
            static S2: [u64; 2] = [0x76f58b0d65bd5553, 0xc06];
            let s: u64 = 0x300e81651c;
            let jf = f.to_bits();
            let dr =
                f64::from_bits(((s >> m) << 63) | (((jf >> 52) & 0x7ff).wrapping_sub(54) << 52));
            let t = (S2[(m >> 5) as usize] >> ((m << 1) & 63)) & 3;
            for k in -1i64..=1 {
                let r = jf.wrapping_add(k as u64);
                if (r & 3) == t {
                    return f64::from_bits(r) + dr;
                }
            }
            break;
        } else {
            b = m - 1;
        }
        m = (a + b) >> 1;
    }
    f
}

