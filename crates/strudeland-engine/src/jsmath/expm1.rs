#[inline(always)]
fn fasttwosum(x: f64, y: f64, e: &mut f64) -> f64 {
    let s = x + y;
    let z = s - x;
    *e = y - z;
    s
}

#[inline(always)]
fn fastsum(xh: f64, xl: f64, yh: f64, yl: f64, e: &mut f64) -> f64 {
    let mut sl = 0.0;
    let sh = fasttwosum(xh, yh, &mut sl);
    *e = (xl + yl) + sl;
    sh
}

#[inline(always)]
fn muldd(xh: f64, xl: f64, ch: f64, cl: f64, l: &mut f64) -> f64 {
    let ahhh = ch * xh;
    *l = (ch * xl + cl * xh) + ch.mul_add(xh, -ahhh);
    ahhh
}

#[inline(always)]
fn mulddd(xh: f64, xl: f64, c: f64, l: &mut f64) -> f64 {
    let h = c * xh;
    *l = c * xl + c.mul_add(xh, -h);
    h
}

#[inline(always)]
fn opolydd(xh: f64, xl: f64, c: &[[f64; 2]], l: &mut f64) -> f64 {
    let mut i = c.len() - 1;
    let mut ch = c[i][0];
    let mut cl = c[i][1];
    while i > 0 {
        i -= 1;
        let cl0 = cl;
        ch = muldd(xh, xl, ch, cl0, &mut cl);
        let cl0 = cl;
        ch = fastsum(c[i][0], c[i][1], ch, cl0, &mut cl);
    }
    *l = cl;
    ch
}

#[inline(always)]
fn opolyddd(x: f64, c: &[[f64; 2]], l: &mut f64) -> f64 {
    let mut i = c.len() - 1;
    let l0 = *l;
    let mut ch = fasttwosum(c[i][0], l0, l);
    let mut cl = c[i][1] + *l;
    while i > 0 {
        i -= 1;
        let cl0 = cl;
        ch = mulddd(ch, cl0, x, &mut cl);
        let cl0 = cl;
        ch = fastsum(c[i][0], c[i][1], ch, cl0, &mut cl);
    }
    *l = cl;
    ch
}

#[inline(always)]
fn as_ldexp(x: f64, i: i64) -> f64 {
    f64::from_bits(x.to_bits().wrapping_add((i as u64) << 52))
}

