// accurate path for 2^-27 <= x
#[cold]
#[inline(never)]
#[allow(non_snake_case)]
fn cos_large_accurate(x: f64) -> f64 {
    let mut r: U128 = 0;
    let mut neg: i32 = 0;
    let k = reduce_large_acc(&mut r, &mut neg, x);

    r <<= 3; // replace r by 8*r
    let u2 = mh_uu(r, r);
    let u4 = mh_uu(u2, u2);
    let u2h = u2 >> 64;

    /* x/(2*pi) mod 1 = k/2^13 + r + eps with |r| <= 2^-14 and 0 <= eps < 2^-127.999
    then cos(x) ~ cos(pi*k/2^12 + 2*pi*r)
                ~ cos(pi*k/2^12)*cos(2*pi*r) - sin(pi*k/2^12)*sin(2*pi*r)
    Write k = 2^12*s + 2^6*i1 + i2 and t1=pi*i1/2^6, t2 = pi*i2/2^12
    then sin(pi*k/2^12) = (-1)^s*[sin(t1)*cos(t2)+cos(t1)*sin(t2)]
    and  cos(pi*k/2^12) = (-1)^s*[cos(t1)*cos(t2)-sin(t1)*sin(t2)]
    */
    let mut sbit = ((k >> 12) & 1) as usize;
    let i1 = ((k >> 6) & 0x3f) as usize;
    let i2 = (k & 0x3f) as usize;

    // approximate |sin(z)| in s1u/2^128
    let s1 = if i1 <= 32 { S1U[i1] } else { S1U[64 - i1] }; // use sin(pi-x) = sin(x)
    // since cos(x) = sin(x+pi/2), we have |C1u[i1]| = |S1u[(i1+32) mod 64]|
    let c1 = if i1 <= 32 { S1U[32 - i1] } else { S1U[i1 - 32] };
    let mut s1u = mh_uu(s1, C2U[i2]);
    let mut t = mh_uu(c1, S2U[i2]);
    // if i1 >= 32, we have to subtract t
    /* s1u/2^128 approximates sin(t1)*cos(t2), and t/2^128 approximates (up to sign)
    sin(t2)*cos(t1), thus s1u +/- t approximates sin(z=t1+t2), but since
    sin(z) >= 0 (0 <= z < pi), we have s1u +/- t >= 0. */
    s1u = if i1 < 32 {
        s1u.wrapping_add(t)
    } else {
        s1u.wrapping_sub(t)
    };

    // approximate cos(z) in c1u/2^128
    let mut c1u = mh_uu(c1, C2U[i2]);
    t = mh_uu(s1, S2U[i2]);
    c1u = if i1 < 32 {
        c1u.wrapping_sub(t)
    } else {
        c1u.wrapping_add(t)
    };

    let Sr = eval_ps(r, u2, u2h, u4); // Sr/2^128 approximates |sin(2*pi*r)|
    let Cr = eval_pc(u2, u2h, u4); // Cr/2^128 approximates cos(2*pi*r)

    // now combine: cos(x) ~ c1*C - s1*S
    c1u = mh_uu(c1u, Cr);
    s1u = mh_uu(s1u, Sr);

    /* c1u/2^128 approximates cos(z)*cos(r) where cos(z) > 0 for i1 < 32,
    and cos(z) <= 0 for i1 >= 32;
    s1u/2^128 approximates sin(z)*sin(r), which has the sign of r. */
    if ((i1 >= 32) as i32 ^ neg) != 0 {
        // cos(z) * r < 0
        c1u = c1u.wrapping_add(s1u);
    } else if c1u <= s1u {
        c1u = s1u - c1u;
        sbit ^= 1;
    } else {
        c1u -= s1u;
    }
    // if i1 >= 32, cos(z) <= 0 thus we should exchange signs
    let ret = u128_tod(c1u, sbit ^ (i1 >= 32) as usize);
    let d = (c1u as u64).wrapping_add(5);
    if d <= 3 {
        return exceptions(x, ret);
    }
    ret
}

// fast path for 2^-27 <= x < 2^31
// adapted from sin.c
// see proof of correctness in cos.pdf
#[inline]
#[allow(non_snake_case)]
fn cr_cos_moderate(x: f64) -> f64 {
    const INVPI: f64 = 5215.189175235227;
    // |invpi/2^14 - 1/pi| < 2^-55.496
    let k = (INVPI * x).round_ties_even();
    // |2^14*(pih + pil) + pi| < 2^-108.041
    let rh = k.mul_add(PIH, x); // rh is exact
    let rl = k * PIL;

    let r = rh + rl; // |r| < 2^-13.339 (see sin.pdf)
    let r2 = r * r;
    let j = k as i64;
    let sbit = ((j >> 14) & 1) as usize; // reduction by an odd multiple of pi?
    let i1 = ((j >> 7) & 0x7f) as usize;
    let i2 = (j & 0x7f) as usize;
    let (mut c1l, mut c2l) = (0.0, 0.0);
    let c1h = muldd(U1[i1][2], U1[i1][3], U2[i2][2], U2[i2][3], &mut c1l);
    // c1h approximates cos(t1)*cos(t2) where t1=i1*pi/2^7 and t2=i2*pi/2^14
    let c2h = muldd(U2[i2][0], U2[i2][1], U1[i1][0], U1[i1][1], &mut c2l);
    // c2h approximates sin(t1)*sin(t2)
    let mut Cl = 0.0;
    let Ch = fastsum(c1h, c1l, -c2h, -c2l, &mut Cl);
    // Ch+Cl approximates cos(t1+t2) = cos(t1)*cos(t2)-sin(t1)*sin(t2)
    let Sh = U1[i1][0] * U2[i2][2] + U1[i1][2] * U2[i2][0];
    // Sh approximates sin(t1+t2) = sin(t1)*cos(t2)+cos(t1)*sin(t2)

    /* for |r| <= 2^-13.339, the polynomial r - 0x1.55555553068fp-3 * r^3
    approximates sin(r) with absolute error < 2^-76.494, and the polynomial
    -0.5 * r^2 + 0x1.55555553bfd3p-5 * r^4 approximates cos(r)-1 with
    absolute error < 2^-92.723 (cf sinmoderate.sollya) */
    let sh = r * (1.0 - 0.16666666659950335 * r2);
    let ch = r2 * (-0.5 + 0.041666666655141404 * r2);
    let mut fh = Ch;
    let mut fl = Cl + Ch * ch - Sh * sh;
    const SGN: [f64; 2] = [1.0, -1.0];
    fh *= SGN[sbit];
    fl *= SGN[sbit];
    const EPS: f64 = 1.0122043719688889e-19;
    let lb = fh + (fl - EPS);
    let ub = fh + (fl + EPS);
    if ub == lb {
        return lb;
    }
    cos_large_accurate(x)
}

// fast path for x >= 2^31
#[inline(never)]
#[allow(non_snake_case, clippy::approx_constant)]
fn cr_cos_large(x: f64) -> f64 {
    let mut r = 0.0;
    let j = reduce_large(&mut r, x);
    // now x/(2pi) ~ k + j/2^15 + r with 0 <= r < 2^-15

    let r2 = r * r;
    let sbit = (j >> 14) as usize; // reduction by an odd multiple of pi?
    let i1 = ((j >> 7) & 0x7f) as usize;
    let i2 = (j & 0x7f) as usize;
    let (mut c1l, mut c2l) = (0.0, 0.0);
    let c1h = muldd(U1[i1][2], U1[i1][3], U2[i2][2], U2[i2][3], &mut c1l);
    let c2h = muldd(U2[i2][0], U2[i2][1], U1[i1][0], U1[i1][1], &mut c2l);
    let mut Cl = 0.0;
    let Ch = fastsum(c1h, c1l, -c2h, -c2l, &mut Cl);
    let Sh = U1[i1][0] * U2[i2][2] + U1[i1][2] * U2[i2][0];

    let sh = r * (6.283185307179586 - 41.341700961418276 * r2);
    let ch = r2 * (-19.739208802178716 + 64.93938786554104 * r2);
    let mut fh = Ch;
    let mut fl = Cl + Ch * ch - Sh * sh;
    const SGN: [f64; 2] = [1.0, -1.0];
    fh *= SGN[sbit];
    fl *= SGN[sbit];
    // fails with eps=0x1.7fp-64 and x=0x1.64dd7934d0fdfp+953 (rndz, no FMA)
    const EPS: f64 = 1.088437337221776e-19;
    let lb = fh + (fl - EPS);
    let ub = fh + (fl + EPS);
    if lb == ub {
        return lb;
    }
    cos_large_accurate(x)
}

pub(super) fn cr_cos(x: f64) -> f64 {
    let z = x.abs();
    let t = z.to_bits();
    let e = (t >> 52) as i32;

    // deal with tiny x to avoid underflow
    if e < 0x3ff - 27 {
        // |x| < 2^-27
        // for |x| < 2^-27, cos(x) rounds to 1 to nearest
        return x.mul_add(-x, 1.0);
    }

    if e < 0x3ff + 31 {
        return cr_cos_moderate(z); // |x| < 2^31
    }

    if e == 0x7ff {
        /* NaN, +Inf and -Inf. */
        // propagate qnan, inf -> qnan, snan -> qnan
        return f64::from_bits(x.to_bits() | (1u64 << 51));
    }

    // now z >= 2^31
    cr_cos_large(z)
}

